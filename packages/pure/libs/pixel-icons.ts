/** Merge each row's runs of '#' into rects so an icon is a handful of <rect>s. */
export function pixelRects(rows: string[]) {
  const rects: { x: number; y: number; w: number }[] = []
  rows.forEach((row, y) => {
    let start = -1
    for (let x = 0; x <= row.length; x++) {
      const on = row[x] === '#'
      if (on && start < 0) start = x
      if (!on && start >= 0) {
        rects.push({ x: start, y, w: x - start })
        start = -1
      }
    }
  })
  return rects
}
